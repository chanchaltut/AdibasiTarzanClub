/** Definitions as plain JSON for the admin panel (functions become a hint string). */
export function schemaForAdmin() {
  const clean = (def) => ({
    ...def,
    titleField: typeof def.titleField === 'function' ? null : def.titleField,
  });
  return {
    collections: COLLECTIONS.map(clean),
    singles: SINGLES,
    aspects: ASPECTS,
    siteLinks: SITE_LINKS,
  };
}

/**
 * Fill choices an item doesn't have yet with their defaults — for items saved before a
 * field existed (e.g. a match's status) and for API calls that leave them out.
 */
export function withDefaults(def, item) {
  const out = def.upgrade ? def.upgrade({ ...item }) : { ...item };
  for (const f of def.fields) {
    if (f.type === 'select' && f.required && f.default !== undefined && (out[f.name] === undefined || out[f.name] === null || out[f.name] === '')) out[f.name] = f.default;
  }
  return out;
}

/** Human title of a stored item, for lists, activity log and messages. */
export function titleOf(def, doc, refs = {}) {
  if (!doc) return '';
  if (typeof def.titleField === 'function') return def.titleField(doc, refs);
  return String(doc[def.titleField] ?? '').trim() || `Untitled ${def.singular}`;
}
